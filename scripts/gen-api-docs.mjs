import { readFileSync, writeFileSync } from "node:fs";
import { parse } from "yaml";

const ROOT = new URL("..", import.meta.url);
const spec = parse(readFileSync(new URL("api/openapi.yaml", ROOT), "utf8"));
const METHODS = ["get", "post", "put", "patch", "delete"];
const GENERATED = "<!-- Generated by scripts/gen-api-docs.mjs from api/openapi.yaml. Do not edit by hand; edit scripts/openapi/*.mjs and run npm run build. -->";

const deref = (x) => {
  let n = x;
  while (n?.$ref) n = n.$ref.split("/").slice(1).reduce((o, k) => o[k], spec);
  return n;
};
const refName = (x) => (x?.$ref ? x.$ref.split("/").pop() : null);
const esc = (s) => String(s ?? "").replace(/\|/g, "\\|").replace(/\n+/g, " ");
const typeOf = (schema) => {
  const s = deref(schema);
  if (!s) return "";
  const name = refName(schema);
  if (name) return name;
  if (s.const !== undefined) return `\`${JSON.stringify(s.const)}\``;
  if (s.enum) return s.enum.filter((v) => v !== null).map((v) => `\`${v}\``).join(", ") + (s.enum.includes(null) ? ", null" : "");
  if (s.oneOf) return s.oneOf.map(typeOf).join(" or ");
  const t = Array.isArray(s.type) ? s.type.join(" or ") : s.type ?? "object";
  if (s.type === "array" || (Array.isArray(s.type) && s.type.includes("array"))) return `array of ${typeOf(s.items) || "any"}`;
  return t;
};
const json = (v) => "```json\n" + JSON.stringify(v, null, 2) + "\n```";
const frontmatter = (title, description) => `---\ntitle: ${JSON.stringify(title)}\ndescription: ${JSON.stringify(description)}\n---\n\n${GENERATED}\n\n# ${title}\n`;

const AUTH_LABEL = { publicApiKey: "public app key", secretApiKey: "secret key", dashboardSession: "dashboard session", googlePubSubOidc: "Pub/Sub push token (optional)", scimToken: "SCIM token" };
function authOf(op) {
  const sec = op.security ?? spec.security;
  if (!sec.length || sec.every((s) => !Object.keys(s).length)) return "none";
  return sec.map((s) => Object.keys(s).map((k) => AUTH_LABEL[k]).join(" + ")).filter(Boolean).join(" or ") || "none";
}

function fieldRows(schema, prefix = "", depth = 0, rows = []) {
  const s = deref(schema);
  if (!s) return rows;
  if (s.allOf) { for (const x of s.allOf) fieldRows(x, prefix, depth, rows); return rows; }
  if (s.oneOf && !s.properties) { for (const x of s.oneOf) fieldRows(x, prefix, depth, rows); return rows; }
  const req = new Set(s.required ?? []);
  for (const [k, v] of Object.entries(s.properties ?? {})) {
    const name = prefix + k;
    if (rows.some((r) => r.name === name)) continue;
    const d = deref(v);
    rows.push({ name, type: typeOf(v), required: req.has(k), description: d?.description ?? "" });
    if (depth < 2 && !refName(v)) {
      if (d?.properties) fieldRows(d, `${name}.`, depth + 1, rows);
      else if (d?.items && deref(d.items)?.properties && !refName(d.items)) fieldRows(d.items, `${name}[].`, depth + 1, rows);
    }
  }
  return rows;
}
const fieldTable = (rows, withRequired = true) => rows.length
  ? [withRequired ? "| Field | Type | Required | Description |\n|---|---|---|---|" : "| Field | Type | Description |\n|---|---|---|",
    ...rows.map((r) => withRequired ? `| \`${r.name}\` | ${esc(r.type)} | ${r.required ? "yes" : "no"} | ${esc(r.description)} |` : `| \`${r.name}\` | ${esc(r.type)} | ${esc(r.description)} |`)].join("\n")
  : "";

function exampleOf(content) {
  if (!content) return undefined;
  if (content.example !== undefined) return content.example;
  const first = content.examples && Object.values(content.examples)[0];
  return first?.value;
}

function curl(method, path, op) {
  const sec = op.security ?? spec.security;
  const keys = sec.flatMap((s) => Object.keys(s));
  const auth = keys[0] === "publicApiKey" ? ' -H "Authorization: Bearer $PUBLIC_KEY"' : keys.includes("secretApiKey") ? ' -H "Authorization: Bearer $SECRET_KEY"' : keys.includes("scimToken") ? ' -H "Authorization: Bearer $SCIM_TOKEN"' : "";
  const EXAMPLE_PARAMS = { project_id: "$PROJECT_ID", app_user_id: "user_1", customer_id: "user_1", entitlement_identifier: "pro", offering_identifier: "default", domain: "app" };
  const url = `$REVENUEDOT_URL${path.replace(/\{(\w+)\}/g, (_, n) => (n === "domain" && path.includes("/sso/domains") ? "acme.com" : EXAMPLE_PARAMS[n] ?? `$${n.toUpperCase()}`))}`;
  // JSON bodies, including SCIM's application/scim+json.
  const [type, content] = Object.entries(op.requestBody?.content ?? {}).find(([t]) => t.includes("json")) ?? [];
  const body = content ? exampleOf(content) : undefined;
  const lines = [`curl -s${method === "get" ? "" : ` -X ${method.toUpperCase()}`} "${url}"${auth}`];
  if (body !== undefined) lines.push(`  -H "Content-Type: ${type}" -d '${JSON.stringify(body).replace(/'/g, "'\\''")}'`);
  return "```bash\n" + lines.join(" \\\n") + "\n```";
}

function renderOp(method, path, op, shared) {
  const out = [`### ${op.summary}`, ""];
  const badges = [`\`${method.toUpperCase()} ${path}\``, `Auth: ${authOf(op)}`];
  if (op["x-revenuedot-extension"]) badges.push("RevenueDot extension");
  if (op["x-scopes"]) badges.push(`Permissions: ${op["x-scopes"].map((s) => `\`${s}\``).join(", ")}`);
  out.push(badges.join(" · "), "");
  if (op.description) out.push(op.description, "");
  const params = [...shared, ...(op.parameters ?? [])].map(deref);
  for (const [where, label] of [["path", "Path parameters"], ["query", "Query parameters"], ["header", "Headers"]]) {
    const ps = params.filter((p) => p.in === where);
    if (!ps.length) continue;
    out.push(`**${label}**`, "", "| Name | Type | Required | Description |", "|---|---|---|---|",
      ...ps.map((p) => `| \`${p.name}\` | ${esc(typeOf(p.schema))} | ${p.required ? "yes" : "no"} | ${esc(p.description)} |`), "");
  }
  const rb = op.requestBody?.content;
  if (rb) {
    const [type, content] = Object.entries(rb)[0];
    out.push(`**Request body** (\`${type}\`)`, "");
    const rows = fieldRows(content.schema);
    if (rows.length) out.push(fieldTable(rows), "");
    else if (deref(content.schema)?.oneOf) out.push(deref(content.schema).oneOf.map((x) => fieldTable(fieldRows(x))).join("\n\nor\n\n"), "");
  }
  out.push("**Example request**", "", curl(method, path, op), "");
  out.push("**Responses**", "");
  for (const [status, r0] of Object.entries(op.responses)) {
    const r = deref(r0);
    const content = r.content?.["application/json"] ?? r.content?.["application/scim+json"];
    const schemaName = content ? refName(content.schema) : null;
    const itemName = content && !schemaName ? refName(deref(content.schema)?.properties?.items?.items) : null;
    const returns = schemaName ? ` Returns [${schemaName}](#${slug(schemaName)}).` : itemName ? ` Returns a list of [${itemName}](#${slug(itemName)}).` : "";
    out.push(`- **${status}**: ${r.description}${returns}`);
  }
  const okStatus = Object.keys(op.responses).find((s) => s.startsWith("2"));
  const okContent = deref(op.responses[okStatus] ?? {})?.content;
  const okExample = okStatus && exampleOf(okContent?.["application/json"] ?? okContent?.["application/scim+json"]);
  if (okExample !== undefined) out.push("", `Example ${okStatus} response:`, "", json(okExample));
  out.push("");
  return out.join("\n");
}

const slug = (h) => h.toLowerCase().replace(/<[^>]+>/g, "").replace(/[^\p{L}\p{N}\s_-]/gu, "").trim().replace(/\s/g, "-");

function opsForPage(page) {
  const tags = spec.tags.filter((t) => t["x-page"] === page);
  const byTag = new Map(tags.map((t) => [t.name, []]));
  for (const [path, item] of Object.entries(spec.paths)) {
    for (const m of METHODS) {
      const op = item[m];
      if (op && byTag.has(op.tags[0])) byTag.get(op.tags[0]).push({ method: m, path, op, shared: item.parameters ?? [] });
    }
  }
  return tags.map((t) => ({ tag: t, ops: byTag.get(t.name) }));
}

function schemasUsed(groups) {
  const names = new Set();
  const visit = (x) => {
    if (!x || typeof x !== "object") return;
    if (x.$ref?.startsWith("#/components/schemas/")) {
      const n = refName(x);
      if (names.has(n)) return;
      names.add(n);
      visit(deref(x));
      return;
    }
    for (const v of Object.values(x)) visit(v);
  };
  for (const g of groups) for (const { op } of g.ops) { visit(op.requestBody); for (const r of Object.values(op.responses)) visit(deref(r)); }
  return [...names].sort();
}

function renderSchemas(names) {
  if (!names.length) return "";
  const out = ["## Objects", "", "The shapes the operations above send and return.", ""];
  for (const n of names) {
    const s = deref({ $ref: `#/components/schemas/${n}` });
    out.push(`### ${n}`, "");
    if (s.description) out.push(s.description, "");
    const rows = fieldRows(s);
    out.push(rows.length ? fieldTable(rows) : "A JSON object.", "");
  }
  return out.join("\n");
}

function operationsPage(page, title, description, intro) {
  const groups = opsForPage(page);
  const count = groups.reduce((n, g) => n + g.ops.length, 0);
  const out = [frontmatter(title, description), intro.trim(), ""];
  out.push("Base URL: your server, for example `http://localhost:8787` or `https://revenuedot.example.com`. The examples read `REVENUEDOT_URL`, `PUBLIC_KEY`, `SECRET_KEY` and `PROJECT_ID` from your shell.", "");
  out.push(`## Operations on this page (${count})`, "");
  for (const g of groups) out.push(`- **${g.tag.name}**: ${g.ops.map(({ op }) => `[${op.summary}](#${slug(op.summary)})`).join(", ")}`);
  out.push("");
  for (const g of groups) {
    out.push(`## ${g.tag.name}`, "", g.tag.description, "");
    for (const o of g.ops) out.push(renderOp(o.method, o.path, o.op, o.shared));
  }
  out.push(renderSchemas(schemasUsed(groups)));
  out.push("## Related", "", "- [API overview](README.md)", "- [Authentication](authentication.md)", "- [Errors](errors.md)", "- [OpenAPI document](openapi.yaml)", "");
  writeFileSync(new URL(`api/${page}.md`, ROOT), out.join("\n").replace(/\n{3,}/g, "\n\n"));
  return count;
}

